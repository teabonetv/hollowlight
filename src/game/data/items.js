export function validateItems() {
  const errors = [];
  const seen = new Set();
  for (const it of ITEMS) {
    if (seen.has(it.id)) errors.push(`duplicate id ${it.id}`);
    seen.add(it.id);
    if (!it.name || !it.flavor) errors.push(`${it.id}: name/flavor required`);
    if (!Number.isInteger(it.sell) || it.sell < 1) errors.push(`${it.id}: sell must be integer ≥1`);
    if (!it.sources?.length) errors.push(`${it.id}: needs a source`);
    if (!it.uses?.length) errors.push(`${it.id}: needs a use`);
    if (it.buy != null && !(Number.isInteger(it.buy) && it.buy > it.sell)) {
      errors.push(`${it.id}: buy ${it.buy} must be integer > sell ${it.sell}`);
    }
  }
  return errors;
}
