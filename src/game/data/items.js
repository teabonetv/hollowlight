function finalize(item) {
  const sources = (item.sources?.length ? item.sources : ['Hearthway stall']).slice();
  const uses = (item.uses?.length ? item.uses : ['Sold for Lumen', 'Altar offering']).slice();
  if (!uses.some((u) => /sold for lumen/i.test(u))) uses.push('Sold for Lumen');
  if (!uses.some((u) => /altar offering/i.test(u)) && item.category !== 'cosmetic') {
    uses.push('Altar offering');
  }
  const obtainable = item.obtainable ?? false;
  return {
    unique: false,
    ...item,
    obtainable,
    // Later-wave goods still appear on the rare shelf so they are not dead.
    rare: item.rare || !obtainable,
    sources,
    uses,
  };
}

export const ITEMS = RAW.map(finalize);

export const ITEMS_BY_ID = Object.fromEntries(ITEMS.map((i) => [i.id, i]));

export function itemName(id) {
  return ITEMS_BY_ID[id]?.name ?? id;
}

