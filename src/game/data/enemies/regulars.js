// Regular enemy roster — pale-things, fog-wights, marsh horrors across the
// twelve stretches. Stats are the data; the combat engine is generic over them.

function loot(entries) {
  return entries;
}

function L(kind, spec) {
  if (kind === 'lumen') return { kind: 'lumen', min: spec[0], max: spec[1], chance: spec[2] ?? 1 };
  return { kind: 'item', id: kind, min: spec[0], max: spec[1], chance: spec[2] ?? 1 };
}

function m(p) {
  return {
    id: p.id,
    name: p.name,
    zoneId: p.z,
    category: p.cat,
    hp: p.hp,
    accuracy: p.acc,
    avoidance: p.avo,
    minDmg: p.min,
    maxDmg: p.max,
    speedMs: p.spd,
    style: p.style,
    weakness: p.weak,
    resist: p.resist,
    xp: p.xp,
    souls: p.souls,
    flavor: p.flavor,
    loot: p.loot,
    boss: false,
  };
}

